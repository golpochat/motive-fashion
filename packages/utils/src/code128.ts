const START_B = 104;
const STOP = 106;
const QUIET = 10;

function pushPattern(out: boolean[], value: number, extraBar = 0) {
  const pattern = PATTERNS[value];
  if (!pattern) throw new Error(`Unknown Code 128 value ${value}`);
  let bar = true;
  for (const width of pattern) {
    for (let i = 0; i < width; i += 1) out.push(bar);
    bar = !bar;
  }
  for (let i = 0; i < extraBar; i += 1) out.push(true);
}

export function encodeCode128Modules(text: string) {
  if (!text) throw new Error('Code 128 needs a value');
  const values = [START_B];
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (code < 32 || code > 126) {
      throw new Error('Code 128B supports printable ASCII only');
    }
    values.push(code - 32);
  }
  let sum = START_B;
  for (let i = 1; i < values.length; i += 1) sum += values[i]! * i;
  values.push(sum % 103);
  const modules: boolean[] = [];
  for (let i = 0; i < QUIET; i += 1) modules.push(false);
  for (const value of values) pushPattern(modules, value);
  pushPattern(modules, STOP, 2);
  for (let i = 0; i < QUIET; i += 1) modules.push(false);
  return modules;
}

export function code128Checksum(text: string) {
  let sum = START_B;
  let pos = 1;
  for (const ch of text) {
    sum += (ch.charCodeAt(0) - 32) * pos;
    pos += 1;
  }
  return sum % 103;
}
